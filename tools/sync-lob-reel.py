#!/usr/bin/env python3
"""Regenerate lob-unwrapped-reel/index.html from lob-unwrapped/index.html.
The reel is the same page forced to a 9:16 stage with only the progress bars.
Run after ANY change to lob-unwrapped/index.html, then re-record the clip:
  python3 tools/sync-lob-reel.py && NODE_PATH=$(npm root -g) node tools/record-clips.js lob-unwrapped-reel
"""
s = open('lob-unwrapped/index.html').read()
def rep(a, b):
    global s
    assert a in s, 'source changed, update the transform: ' + a[:60]
    s = s.replace(a, b)
rep('.stage{position:relative;flex:none;width:min(100vw,calc((100dvh - 49px)*16/9));height:min(calc(100dvh - 49px),calc(100vw*9/16));',
    '.stage{position:relative;flex:none;width:min(100vw,calc((100dvh - 49px)*9/16));height:min(calc(100dvh - 49px),calc(100vw*16/9));')
rep('@media(max-aspect-ratio:1/1){.stage{width:100vw;height:calc(100dvh - 49px)}}\n', '')
rep('<title>Lob Unwrapped</title>', '<title>Lob Unwrapped Reel</title>')
rep('<b>Lob Unwrapped</b></nav>', '<b>Lob Unwrapped Reel</b></nav>')
rep('lob-unwrapped/thumb.png', 'lob-unwrapped-reel/thumb.png')
rep('.clip .toast{display:none}', '.clip .toast{display:none}\n/* standalone reel: just the 9:16 picture and its progress bars */\n#hShare,.dock{display:none!important}\nbody{align-items:center}')
# slide 1 subtitle on three lines
rep("'’s year in <i style=\"color:#fff\">direct mail</i>'", "'’s<br>year in<br><i style=\"color:#fff\">direct mail</i>'")

# reel-only layout: smaller type, and the visual sits in the bottom third (starts on the lower-third line)
REEL_CSS = """
/* ---------- reel layout (generated by tools/sync-lob-reel.py) ---------- */
@container (max-aspect-ratio:1/1){
  .stage>*{--ah:calc(33.333cqh - var(--u)*20)}
  .in:not(.ctr):not(:has(.cswrap)){grid-template-rows:minmax(0,1fr) 33.333cqh;row-gap:0;padding-bottom:0;align-items:start}
  .in:not(:has(.cswrap)) .art{align-self:stretch;align-items:center;justify-content:center;padding:calc(var(--u)*1) 0 calc(var(--u)*13);overflow:visible}
  .art:not(:has(.cswrap))>.rise{height:var(--ah);display:flex;align-items:center;justify-content:center}
  .art .tun.round{width:var(--ah);height:var(--ah)}
  .art>.rise>.tun:not(.round){width:100%;height:var(--ah)}
  .arts{width:calc(var(--ah)*1.04);margin:0;max-width:none}
  .map{width:calc(var(--ah)*1.85);margin:0 -10% 0 0}
  .rankwrap{gap:calc(var(--u)*2.4)}
  .rankwrap .lead{font-size:calc(var(--u)*4.6)}
  .rank{gap:calc(var(--u)*1.4)}
  .rank .n{font-size:calc(var(--u)*6.4)}.rank .nm{font-size:calc(var(--u)*4.4)}.rank .t{height:calc(var(--u)*1.8);margin-top:calc(var(--u)*1)}
  .in.col:not(.ctr):not(:has(.cswrap)){justify-content:flex-start;padding-bottom:calc(var(--u)*13)}
  .in.col .mixrow{margin-top:auto;min-height:var(--ah);align-content:center}
  .k{font-size:calc(var(--u)*3.4)}
  .h,.h.sm{font-size:calc(var(--u)*8.6)}
  .hero{font-size:calc(var(--u)*13.5)}
  .tx:has(.hero) .lead{font-size:calc(var(--u)*6);line-height:1.12}
  .lead{font-size:calc(var(--u)*7)}
  .big,.big.md{font-size:12.5cqw}.big.lg{font-size:19cqw}
  .sub{font-size:calc(var(--u)*4.4)}.fine{font-size:calc(var(--u)*3.2)}.pill{font-size:calc(var(--u)*3.4)}
  .tx{gap:calc(var(--u)*3)}
}
"""
i = s.index('</style>')
s = s[:i] + REEL_CSS + s[i:]
open('lob-unwrapped-reel/index.html', 'w').write(s)
